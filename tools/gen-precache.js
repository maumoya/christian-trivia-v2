// Writes precache-list.js: every file the app ships, so it works offline after one visit.
// Run: node tools/gen-precache.js
import fs from 'node:fs';

const files = ['./', './index.html', './main.js', './manifest.webmanifest', './precache-list.js'];
const walk = (d) => fs.readdirSync(d, { withFileTypes: true })
  .sort((a, b) => a.name.localeCompare(b.name))
  .forEach((e) => (e.isDirectory() ? walk(`${d}/${e.name}`) : files.push(`./${d}/${e.name}`)));
walk('src');
walk('icons');
fs.writeFileSync('precache-list.js', `// Generated by tools/gen-precache.js. Do not edit by hand.\nexport const PRECACHE = ${JSON.stringify(files, null, 2)};\n`);
console.log(`${files.length} files listed`);
